import { test, expect } from '@playwright/test'

test('侧栏分组可以收起，设备图标区分在线状态', async ({ page }) => {
  await page.goto('/')
  const devices = page.locator('#nav-devices')
  const online = devices.getByRole('button', { name: '大娃家', exact: true })
  const inactive = devices.getByRole('button', { name: '朋友的电脑', exact: true })
  await expect(online.locator('.device-icon')).toHaveCSS('background-color', 'rgb(55, 133, 255)')
  await expect(inactive.locator('.device-icon')).toHaveCSS('background-color', 'rgb(169, 173, 180)')
  const toggle = page.getByRole('button', { name: '我的设备', exact: true })
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(devices).toBeHidden()
  await toggle.click()
  await expect(online).toBeVisible()
})

test('设置页和悬浮面板共用画质预设和码率滑块', async ({ page }) => {
  await page.goto('/#/app/moonlight')
  const quality = page.locator('.quality-fields')
  await quality.getByLabel('分辨率').selectOption('2560x1440')
  await quality.getByLabel('帧率').selectOption('120')
  await quality.getByRole('slider', { name: '码率' }).fill('42')
  await expect(quality.getByRole('slider')).toHaveAttribute('aria-valuetext', '42 Mbps')
  const bitrate = quality.getByRole('spinbutton', { name: '码率数值（Mbps）' })
  await expect(bitrate).toHaveValue('42')
  await bitrate.fill('55.5')
  await expect(quality.getByRole('slider')).toHaveAttribute('aria-valuetext', '55.5 Mbps')
  await expect(quality.getByLabel('分辨率')).toHaveValue('2560x1440')
  await expect(quality.getByLabel('帧率')).toHaveValue('120')
  await page.goto('/?window=session')
  await page.getByRole('button', { name: '打开会话悬浮球设置' }).click()
  await expect(quality.getByRole('combobox', { name: '分辨率', exact: true })).toBeVisible()
  await expect(quality.getByRole('combobox', { name: '帧率', exact: true })).toBeVisible()
  await expect(quality.getByRole('slider', { name: '码率' })).toBeVisible()
  await expect(quality.getByRole('spinbutton', { name: '码率数值（Mbps）' })).toBeVisible()
  await page.locator('.session-surface').click({ position: { x: 1, y: 1 } })
  await expect(page.getByRole('region', { name: '本次远控设置' })).toBeHidden()
  await expect(page.getByRole('button', { name: '打开会话悬浮球设置' })).toBeVisible()
})

test('悬停设备可删除，确认后从侧栏移除', async ({ page }) => {
  await page.goto('/')
  const list = page.locator('#nav-devices')
  const device = list.getByRole('button', { name: '大娃家', exact: true })
  const remove = list.getByRole('button', { name: '删除 大娃家', exact: true })
  await expect(remove).toHaveCSS('opacity', '0')
  await device.hover()
  await expect(remove).toHaveCSS('opacity', '1')
  await remove.click()
  const dialog = page.getByRole('dialog', { name: '删除设备' })
  await dialog.getByRole('button', { name: '取消' }).click()
  await expect(device).toBeVisible()
  await device.hover()
  await remove.click()
  await dialog.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByRole('heading', { name: '开始协助', exact: true })).toBeVisible()
  await expect(device).toHaveCount(0)
})

